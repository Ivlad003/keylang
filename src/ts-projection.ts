// TypeScript projection of the planned declarations (`keylang types`,
// .scratch/type-fields §6): how the intentions of the specs read as
// TypeScript interfaces before any of them is written.
//
// Place in the pipeline: a pure view over SpecIR (`planned` with their
// fields) and the snapshot's nodes; it reads and writes nothing. The CLI
// prints or writes its text; a web page may render its items. Entry points:
// `projectTypes` (the text and one item per declaration) and
// `plannedIdsOf` (the planned IDs of named flows or features).
//
// Rules: a `planned type` with fields is an interface, with `= X` an alias,
// with neither `unknown` and a TODO; `planned fn` are methods of an
// interface named after their parent module; an ID the code already has in
// a TypeScript file is an `import type`. Items are ordered by ID and the text
// is byte-stable for the same inputs.

import { posix } from "node:path";
import { specPath } from "./config.ts";
import type { AnalysisSnapshot } from "./snapshot.ts";
import { compareText } from "./span.ts";
import type { Planned, SpecIR } from "./spec-ir.ts";

/** What to project: the specs, the code (null without one), which IDs and where the text will live. */
export interface ProjectionInput {
  spec: Pick<SpecIR, "planned">;
  snapshot: Pick<AnalysisSnapshot, "nodes"> | null;
  /** The IDs to project; absent: every `planned` of the specs. An ID the code has in a TypeScript file becomes an `import type`. */
  ids?: readonly string[];
  /** The repository-relative POSIX directory of the output file, for the `import type` paths; absent: the root. */
  outDir?: string;
}

/** One declaration of the projection, in output order. */
export interface ProjectedItem {
  /** The keylang ID: of the planned type or module, or of the parent module of planned fns. */
  id: string;
  /** The TypeScript name: the last ID segment in PascalCase, or the code's name for an import. */
  name: string;
  /** `interface`, `alias` (`type X = …`, `unknown` included) or `import` (the code already has it). */
  form: "interface" | "alias" | "import";
  /** Where it comes from: the spec line of the declaration, or the code's file and line for an import. */
  file: string;
  line: number;
  /** Its TypeScript text: the import line, or the doc comment and the declaration. */
  text: string;
}

/** The whole projection: the file text and its items. */
export interface Projection {
  text: string;
  items: ProjectedItem[];
}

/** The planned IDs of named flows or features, and the names that are neither. */
export interface PlannedSelection {
  ids: string[];
  unknown: string[];
}

/** The first line of the projection: what wrote it, so `--out` knows a file it may replace. */
export const PROJECTION_HEADER = "// keylang:generated by `keylang types` from the planned declarations; edit the specs, not this file.";

/** A TypeScript identifier that needs no quotes as a member name. */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** A file whose types an `import type` can name. */
const TS_FILE = /\.(ts|tsx|mts|cts)$/;

/** The projection of the selected planned declarations, imports first, then declarations by ID. */
export function projectTypes(input: ProjectionInput): Projection {
  // The first declaration of each ID wins, as in `check` (a repeat is K002).
  const planned = new Map<string, Planned>();

  for (const item of input.spec.planned) if (!planned.has(item.id)) planned.set(item.id, item);
  const nodes = input.snapshot?.nodes ?? {};
  const selected = [...new Set(input.ids ?? [...planned.keys()])].sort(compareText);
  const imports: { item: ProjectedItem; path: string }[] = [];
  const types: ProjectedItem[] = [];
  /** Parent module ID → its planned fns, for the module interfaces. */
  const groups = new Map<string, Planned[]>();

  // Sort each selected ID into an import, a type, or a module group.
  for (const id of selected) {
    const code = nodes[id];

    if (code) {
      const imported = importItem(id, code, input.outDir ?? "");

      if (imported) imports.push(imported);
      continue;
    }

    const item = planned.get(id);

    if (!item) continue;

    if (item.decl === "type") types.push(typeItem(item));
    else if (item.decl === "module") addToGroup(groups, id, null);
    else if (item.decl === "fn" && id.includes(".")) addToGroup(groups, parentOf(id), item);
  }

  // A selected planned module takes all its planned fns the code does not have yet.
  const modulesSelected = new Set(selected.filter((id) => planned.get(id)?.decl === "module" && !nodes[id]));

  for (const item of planned.values()) {
    if (item.decl === "fn" && item.id.includes(".") && modulesSelected.has(parentOf(item.id)) && !nodes[item.id]) addToGroup(groups, parentOf(item.id), item);
  }

  const modules = [...groups].map(([id, fns]) => moduleItem(id, planned.get(id) ?? null, fns));
  const declarations = [...types, ...modules].sort((a, b) => compareText(a.id, b.id));
  const items = [...imports.map((i) => i.item), ...declarations];

  return { text: projectionText(imports, declarations), items };
}

/**
 * The planned IDs of named flows or features, in spec order: a flow's are the
 * `planned` lines of its section, a feature's those of
 * `<dir>/features/<name>.md`. `unknown` lists the names that are neither.
 */
export function plannedIdsOf(spec: Pick<SpecIR, "planned" | "flows">, names: readonly string[], specDir: string): PlannedSelection {
  const ids: string[] = [];
  const unknown: string[] = [];

  for (const name of names) {
    const flow = spec.flows.find((f) => f.name === name);
    const feature = specPath(specDir, `features/${name}.md`);
    // A flow owns the planned lines from its heading to the next flow heading of its file.
    const next = flow ? Math.min(...spec.flows.filter((f) => f.file === flow.file && f.span.start.line > flow.span.start.line).map((f) => f.span.start.line)) : Infinity;
    const owned = flow ? spec.planned.filter((p) => p.file === flow.file && p.span.start.line > flow.span.start.line && p.span.start.line < next) : spec.planned.filter((p) => p.file === feature);

    if (!flow && !spec.flows.some((f) => f.file === feature) && owned.length === 0) unknown.push(name);

    for (const p of owned) if (!ids.includes(p.id)) ids.push(p.id);
  }

  return { ids, unknown };
}

/** Adds a planned fn (or only the group, for a planned module) to the group of `module`. */
function addToGroup(groups: Map<string, Planned[]>, module: string, fn: Planned | null): void {
  const fns = groups.get(module) ?? [];

  if (fn && !fns.some((f) => f.id === fn.id)) fns.push(fn);
  groups.set(module, fns);
}

/** `import type { X } from "<path>"` for a code type or class in a TypeScript file, with that path; null for any other node. */
function importItem(id: string, code: AnalysisSnapshot["nodes"][string], outDir: string): { item: ProjectedItem; path: string } | null {
  const isType = code.kind === "type" || (code.kind === "module" && code.class === true);

  if (!isType || code.file === null || !TS_FILE.test(code.file)) return null;
  const name = code.name ?? lastSegment(id);
  const relative = posix.relative(outDir === "" ? "." : outDir, code.file);
  const path = relative.startsWith(".") ? relative : `./${relative}`;

  return { item: { id, name, form: "import", file: code.file, line: code.line ?? 1, text: `import type { ${name} } from ${JSON.stringify(path)};` }, path };
}

/** A planned type: an interface with its fields (and `extends`), an alias for `= X`, or `unknown` with a TODO. */
function typeItem(item: Planned): ProjectedItem {
  const name = pascalCase(lastSegment(item.id));
  const signature = item.signature ?? "";
  const doc = docComment(item.id, item.file, item.span.start.line);
  const at = { id: item.id, name, file: item.file, line: item.span.start.line };

  // `= X`: the alias the plan writes; fields under it are K005 and ignored here.
  if (signature.startsWith("=")) return { ...at, form: "alias", text: `${doc}\nexport type ${name} = ${withoutSemicolon(signature.slice(1).trim())};` };
  const heritage = signature.startsWith("extends ") ? ` ${signature}` : "";
  const fields = item.fields ?? [];

  if (fields.length === 0 && heritage === "") {
    const note = signature === "" ? "" : ` ${signature}`;

    return { ...at, form: "alias", text: `${doc}\nexport type ${name} = unknown; // TODO: fields${note}` };
  }

  // A repeated field name is K002; as in `check`, the first one counts.
  const unique = fields.filter((f, i) => fields.findIndex((other) => other.name === f.name) === i);
  const lines = unique.map((f) => `  ${memberName(f.name)}${f.optional ? "?" : ""}: ${withoutSemicolon(f.type)};`);
  const body = lines.length === 0 ? " {}" : ` {\n${lines.join("\n")}\n}`;

  return { ...at, form: "interface", text: `${doc}\nexport interface ${name}${heritage}${body}` };
}

/** The interface of a module: its planned fns as methods, by ID; placed at the planned module, else at its first fn. */
function moduleItem(id: string, module: Planned | null, fns: readonly Planned[]): ProjectedItem {
  const sorted = [...fns].sort((a, b) => compareText(a.id, b.id));
  const place = module ?? sorted[0]!;
  const name = pascalCase(lastSegment(id));
  const lines = sorted.map((fn) => `  ${method(fn)}`);
  const body = lines.length === 0 ? " {}" : ` {\n${lines.join("\n")}\n}`;

  return { id, name, form: "interface", file: place.file, line: place.span.start.line, text: `${docComment(id, place.file, place.span.start.line)}\nexport interface ${name}${body}` };
}

/**
 * A planned fn as a method: `(x: T) → R` is `f(x: T): R;` (`->`, `=>` and a
 * TypeScript-style `: R` mark the result too), a parameter list
 * alone returns `unknown`, no signature takes any arguments. A signature of
 * another shape is kept as a comment beside the open form.
 */
function method(fn: Planned): string {
  const name = memberName(lastSegment(fn.id));
  const signature = fn.signature?.trim() ?? "";
  const open = `${name}(...args: unknown[]): unknown;`;

  if (signature === "") return open;
  const close = closingParen(signature);

  if (!signature.startsWith("(") || close === null) return `${open} // ${signature}`;
  const params = signature.slice(0, close + 1);
  const rest = signature.slice(close + 1).trim();
  // The result marker: keylang's `→`/`->`, an arrow type's `=>`, or a method's `:`.
  const arrow = /^(→|->|=>|:)\s*/.exec(rest);

  if (rest === "") return `${name}${params}: unknown;`;

  if (!arrow) return `${open} // ${signature}`;
  const result = withoutSemicolon(rest.slice(arrow[0].length).trim());

  return `${name}${params}: ${result === "" ? "unknown" : result};`;
}

/** The index of the `)` that closes the `(` at index 0, or null when it does not close. */
function closingParen(text: string): number | null {
  let depth = 0;

  for (let i = 0; i < text.length; i++) {
    if (text[i] === "(") depth++;
    else if (text[i] === ")" && --depth === 0) return i;
  }

  return null;
}

/** The file: the header, the imports, then the declarations, blank lines between, one final newline. */
function projectionText(imports: readonly { item: ProjectedItem; path: string }[], declarations: readonly ProjectedItem[]): string {
  const blocks = [PROJECTION_HEADER];
  // One `import type` line per file, names sorted, files in path order.
  const byPath = new Map<string, string[]>();

  for (const { item, path } of imports) byPath.set(path, [...(byPath.get(path) ?? []), item.name]);

  if (byPath.size > 0) blocks.push([...byPath].sort(([a], [b]) => compareText(a, b)).map(([path, names]) => `import type { ${[...new Set(names)].sort(compareText).join(", ")} } from ${JSON.stringify(path)};`).join("\n"));

  for (const d of declarations) blocks.push(d.text);

  return `${blocks.join("\n\n")}\n`;
}

/** `/** <id> — <spec file>:<line> *\/` above a declaration. */
function docComment(id: string, file: string, line: number): string {
  return `/** ${id} — ${file}:${line} */`;
}

/** A member name as TypeScript accepts it: bare when an identifier, else quoted. */
function memberName(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/** `order-line` → `OrderLine`, `orders` → `Orders`; a leading digit gets `_`. */
function pascalCase(segment: string): string {
  const name = segment
    .split(/[^A-Za-z0-9_$]+/)
    .filter((part) => part !== "")
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");

  return name === "" || /^[0-9]/.test(name) ? `_${name}` : name;
}

/** A type without the `;` a plan may end it with. */
function withoutSemicolon(type: string): string {
  return type.replace(/;\s*$/, "");
}

/** The last dotted segment of an ID. */
function lastSegment(id: string): string {
  return id.slice(id.lastIndexOf(".") + 1);
}

/** The ID without its last segment. */
function parentOf(id: string): string {
  return id.slice(0, id.lastIndexOf("."));
}
